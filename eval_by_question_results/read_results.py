import pandas as pd
import numpy as np
def read_results(file_path):
    data = pd.read_parquet(file_path)
    # data_source, length, reward, uid
    data_sources = data['data_source'].unique()
    dataset_reward = {k: {'all': []} for k in data_sources}
    print(len(data['uid'].unique()), len(data))
    for i in range(len(data)):
        data_source = data.iloc[i]['data_source']
        length = data.iloc[i]['length']
        reward = data.iloc[i]['reward']
        uid = data.iloc[i]['uid']
        if uid not in dataset_reward[data_source]:
            dataset_reward[data_source][uid] = [reward]
        else:
            dataset_reward[data_source][uid].append(reward)
        dataset_reward[data_source]['all'].append(reward)
    print("result of " + file_path + ":")
    all_avg = 0
    N = 8
    all_scores = [0 for _ in range(N)]
    for source in data_sources:
        print("===================================")
        print(source)
        print("avg reward:", np.mean(dataset_reward[source]['all']))
        all_avg += np.mean(dataset_reward[source]['all'])
        result_by_seed = [[] for _ in range(N)]
        for j in range(N):
            for uid in dataset_reward[source].keys():
                if uid == 'all':
                    continue
                result_by_seed[j].append(dataset_reward[source][uid][j])
            all_scores[j] += np.array(result_by_seed[j]).mean() / len(data_sources)
            # print(j, len(result_by_seed[j]))
        print("std reward:", np.array(result_by_seed).mean(-1).std())
        print(f"pass @ {N}:", np.array(result_by_seed).max(0).mean()) 
        print("===================================")
    print("all avg reward:", all_avg / len(data_sources))
    print("all scores:", np.array(all_scores).std())


